import type { SqlExecutor } from '../../db/sql.js';

/**
 * Transactional outbox for cell-index writes (table `cell_index_outbox`, migration 0009).
 *
 * The API inserts a row in the same Aurora transaction as the place or push-target change. After
 * the commit it still writes through to DynamoDB and deletes the row on success. A scheduled
 * drainer (drainer.ts) redoes any row that is left. Like repair messages, a row names WHAT to look
 * at (op, cell, place), never what to write: the drainer re-reads Aurora and applies the truth, so
 * it is idempotent and order-independent.
 */
export interface OutboxEntry {
  /** Generated by the caller so it can delete the row after the write-through. */
  id: string;
  op: 'put' | 'remove' | 'update';
  /** '' for an update of all of the device's places. */
  h3Cell: string;
  placeId: string;
}

export interface OutboxRow {
  id: string;
  deviceId: string;
  op: 'put' | 'remove' | 'update';
  h3Cell: string;
  placeId: string;
  attempts: number;
  createdAt: string;
}

/** Inserts an outbox row inside an open transaction. */
export async function insertOutboxRow(
  tx: SqlExecutor,
  deviceId: string,
  entry: OutboxEntry,
): Promise<void> {
  await tx.query(
    `INSERT INTO cell_index_outbox (id, device_id, op, payload)
     VALUES ($1::uuid, $2::uuid, $3, $4::jsonb)`,
    [
      entry.id,
      deviceId,
      entry.op,
      JSON.stringify({ h3Cell: entry.h3Cell, placeId: entry.placeId }),
    ],
  );
}

export interface OutboxStats {
  pending: number;
  maxAttempts: number;
  /** Age of the oldest row, in seconds (0 when empty). */
  oldestAgeSeconds: number;
}

export interface CellIndexOutbox {
  /** Deletes rows after their write succeeded. Missing ids are fine. */
  remove(ids: string[]): Promise<void>;
  /**
   * Claims up to `limit` rows older than `olderThanMs`, oldest first, and increments `attempts`
   * on each in the same statement (so a row that keeps failing is counted even if the drainer
   * crashes). Returns the rows with the incremented count.
   */
  claimDue(olderThanMs: number, limit: number, now?: Date): Promise<OutboxRow[]>;
  stats(now?: Date): Promise<OutboxStats>;
}

interface Row {
  id: string;
  device_id: string;
  op: 'put' | 'remove' | 'update';
  payload: { h3Cell?: string; placeId?: string } | string;
  attempts: number;
  created_at: string;
}

export class PostgresCellIndexOutbox implements CellIndexOutbox {
  constructor(private readonly db: SqlExecutor) {}

  async remove(ids: string[]): Promise<void> {
    if (ids.length === 0) return;
    await this.db.query(
      `DELETE FROM cell_index_outbox
        WHERE id IN (SELECT jsonb_array_elements_text($1::jsonb)::uuid)`,
      [JSON.stringify(ids)],
    );
  }

  async claimDue(olderThanMs: number, limit: number, now: Date = new Date()): Promise<OutboxRow[]> {
    const cutoff = new Date(now.getTime() - olderThanMs).toISOString();
    const rows = await this.db.query<Row>(
      `UPDATE cell_index_outbox SET attempts = attempts + 1
        WHERE id IN (SELECT id FROM cell_index_outbox
                      WHERE created_at < $1::timestamptz
                      ORDER BY created_at LIMIT $2::int)
       RETURNING id, device_id, op, payload, attempts,
                 to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') AS created_at`,
      [cutoff, limit],
    );
    return rows
      .map((r) => {
        const payload =
          typeof r.payload === 'string'
            ? (JSON.parse(r.payload) as { h3Cell?: string; placeId?: string })
            : r.payload;
        return {
          id: r.id,
          deviceId: r.device_id,
          op: r.op,
          h3Cell: payload.h3Cell ?? '',
          placeId: payload.placeId ?? '',
          attempts: r.attempts,
          createdAt: r.created_at,
        };
      })
      .sort((a, b) => a.createdAt.localeCompare(b.createdAt));
  }

  async stats(now: Date = new Date()): Promise<OutboxStats> {
    const rows = await this.db.query<{
      pending: number | string;
      max_attempts: number | null;
      oldest: string | null;
    }>(
      `SELECT count(*)::int AS pending, max(attempts)::int AS max_attempts,
              extract(epoch FROM ($1::timestamptz - min(created_at)))::float8 AS oldest
         FROM cell_index_outbox`,
      [now.toISOString()],
    );
    const r = rows[0];
    return {
      pending: Number(r?.pending ?? 0),
      maxAttempts: r?.max_attempts ?? 0,
      oldestAgeSeconds: Math.max(0, Math.round(Number(r?.oldest ?? 0))),
    };
  }
}
